-- Workflow state. The owner-rights procedures write it and the apps read it.

DEFINE TABLE {{ app_db }}.CORE.CHANGE_REQUESTS (
    REQUEST_ID          VARCHAR       NOT NULL COMMENT 'UUID',
    TABLE_ID            VARCHAR       NOT NULL COMMENT 'Key into V_MANAGED_TABLES',
    SOURCE_FQN          VARCHAR       NOT NULL COMMENT 'Managed table at request time',
    STATUS              VARCHAR       NOT NULL COMMENT 'See auditable_crud/state.py',
    REQUESTED_BY        VARCHAR       NOT NULL,
    CLONE_DATABASE      VARCHAR       NOT NULL,
    CLONE_SCHEMA        VARCHAR       NOT NULL,
    SANDBOX_BASE        VARCHAR       NOT NULL COMMENT 'Base name of clone / stream / diff objects',
    SNAPSHOT_NS         NUMBER(38, 0) COMMENT 'Epoch ns the clone was taken AT (drift baseline)',
    SQL_TEXT            VARCHAR       COMMENT 'SQL as typed or generated',
    CANONICAL_SQL       VARCHAR       COMMENT 'Guarded, fully qualified SQL that is executed',
    SQL_SHA256          VARCHAR,
    STATEMENT_KIND      VARCHAR,
    NL_PROMPT           VARCHAR       COMMENT 'Natural-language prompt, when AI generated the SQL',
    DRY_RUN_COUNTS      VARIANT       COMMENT 'Rows affected reported by the DML on the clone',
    DRY_RUN_DIFF_COUNTS VARIANT       COMMENT 'Rows affected according to the stream',
    DRY_RUN_FINGERPRINT VARCHAR       COMMENT 'HASH_AGG of the change set',
    DRY_RUN_QUERY_ID    VARCHAR,
    DRY_RUN_ELAPSED_MS  NUMBER(38, 0),
    DRY_RUN_AT          TIMESTAMP_LTZ,
    SUBMITTED_AT        TIMESTAMP_LTZ,
    SUBMIT_NOTE         VARCHAR,
    CANCELLED_AT        TIMESTAMP_LTZ,
    REVAL_SNAPSHOT_NS   NUMBER(38, 0) COMMENT 'Snapshot of the admin re-validation clone',
    REVAL_COUNTS        VARIANT,
    REVAL_FINGERPRINT   VARCHAR,
    REVAL_MATCHES       BOOLEAN       COMMENT 'Re-validation produced the same change set',
    REVAL_BY            VARCHAR,
    REVAL_AT            TIMESTAMP_LTZ,
    REVIEWED_BY         VARCHAR,
    REVIEWED_AT         TIMESTAMP_LTZ,
    REVIEW_COMMENT      VARCHAR,
    APPROVED_SHA256     VARCHAR       COMMENT 'Hash of the exact SQL that was approved',
    TOLERANCE_PCT       FLOAT         COMMENT 'Allowed rows-affected deviation at execution',
    EXECUTED_BY         VARCHAR,
    EXEC_COUNTS         VARIANT,
    EXEC_QUERY_ID       VARCHAR,
    EXEC_ELAPSED_MS     NUMBER(38, 0),
    EXECUTED_AT         TIMESTAMP_LTZ,
    LAST_ERROR          VARCHAR,
    SANDBOX_DROPPED_AT  TIMESTAMP_LTZ,
    CREATED_AT          TIMESTAMP_LTZ NOT NULL,
    UPDATED_AT          TIMESTAMP_LTZ NOT NULL,
    REVISION            NUMBER(38, 0) COMMENT 'Bumped when a sandbox run starts (compare-and-set)',
    RUN_REVISION        NUMBER(38, 0) COMMENT 'REVISION of the latest completed sandbox run',
    DRY_SANDBOX_REVISION NUMBER(38, 0) COMMENT 'Published developer sandbox revision; null for legacy names',
    REVAL_SANDBOX_REVISION NUMBER(38, 0) COMMENT 'Published review sandbox revision; null for legacy names',
    RUN_CONTEXT_VERSION NUMBER(38, 0) COMMENT 'Version of the DML settings used for the latest completed run',
    CONSTRAINT PK_CHANGE_REQUESTS PRIMARY KEY (REQUEST_ID)
)
COMMENT = 'One row per DML change request';

DEFINE TABLE {{ app_db }}.CORE.AUDIT_LOG (
    EVENT_ID   NUMBER(38, 0) AUTOINCREMENT START 1 INCREMENT 1 ORDER,
    EVENT_AT   TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    REQUEST_ID VARCHAR       NOT NULL,
    EVENT      VARCHAR       NOT NULL,
    ACTOR      VARCHAR       NOT NULL,
    DETAILS    VARIANT
)
COMMENT = 'Append-only audit trail of every change-request event';
